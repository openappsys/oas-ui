/** hex 行（每行 = 一条模块行，高位在左）还原为模块矩阵 */
function modulesFromRows(rows: string[], size: number): Uint8Array {
  const modules = new Uint8Array(size * size)
  rows.forEach((hex, y) => {
    const bits = BigInt(`0x${hex}`).toString(2).padStart(size, '0')
    for (let x = 0; x < size; x++) modules[y * size + x] = bits[x] === '1' ? 1 : 0
  })
  return modules
}

describe('QR 编码器已知答案向量（四级别 × 多版本，矩阵逐位一致）', () => {
  for (const [key, v] of Object.entries(VECTORS)) {
    it(`${key} → v${v.version} / mask ${v.mask}`, () => {
      const qr = encodeQR(v.value, v.level)
      expect(qr.version).toBe(v.version)
      expect(qr.mask).toBe(v.mask)
      expect(qr.size).toBe(v.rows.length)
      expect(qr.modules).toEqual(modulesFromRows(v.rows, qr.size))
    })
  }

  it('v40-L 容量边界：2953 字节可编码，2954 抛 QR_TOO_LONG', () => {
    expect(encodeQR('x'.repeat(2953), 'l').version).toBe(40)
    expect(() => encodeQR('x'.repeat(2954), 'l')).toThrow('QR_TOO_LONG')
  })
})
